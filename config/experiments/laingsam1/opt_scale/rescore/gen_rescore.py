"""Generate the rescoring configs: score every phase 1 final checkpoint on one fixed validation set.

Usage, from the repo root:
  python3 config/experiments/laingsam1/opt_scale/rescore/gen_rescore.py

Writes rescore_<optimizer>.yaml next to this script. What it is for: README.md here.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "sweep100m")
OPTS = ["adam", "muon", "muown_classical"]
N_VALID = 25600   # validation sequences scored, the same ones for every checkpoint

HEADER = """# @package _global_
#
# rescore / {opt}: score every final checkpoint of the phase 1 sweep on one fixed validation set.
# Why: README.md in this folder. No training; the phase 1 folders are only read.
#
#   batch size : 128, 256, 512        lr : 2.5e-4, 5.e-4, 1.e-3, 2.e-3, 4.e-3, 8.e-3
#   budget     : 1x, 2x, 4x  (the final checkpoint of cooldown1x / cooldown2x / cooldown4x)
# = 54 jobs of about 11 minutes on one node.
#
# Job index = (batch_i x 6 + lr_i) x 3 + budget_i     (budget_i: 0 = 1x, 1 = 2x, 2 = 4x)
#   batch 128: 0-17   batch 256: 18-35   batch 512: 36-53
#
# Validation set: the first {n:,} sequences of the held-out 1 % split, read in fixed order
# (dataloader 'single', evaluation only), identical for every job.
#
#   python scripts/run_autoexp.py --config-name experiments/laingsam1/opt_scale/rescore/rescore_{opt} --dry-run
#   python scripts/run_autoexp.py --config-name experiments/laingsam1/opt_scale/rescore/rescore_{opt}
#
# Generated by gen_rescore.py from ../sweep100m/phase1_{opt}.yaml.

"""

SWEEP = """sweep:
  type: product
  groups:
    # batch size
    - type: list
      configs:
        - {backend.aux.gbs: 128}
        - {backend.aux.gbs: 256}
        - {backend.aux.gbs: 512}
    # learning rate
    - type: list
      configs:
        - {backend.megatron.lr: 2.5e-4}
        - {backend.megatron.lr: 5.e-4}
        - {backend.megatron.lr: 1.e-3}
        - {backend.megatron.lr: 2.e-3}
        - {backend.megatron.lr: 4.e-3}
        - {backend.megatron.lr: 8.e-3}
    # budget: which cooldown's final checkpoint is scored
    - type: list
      configs:
        - {stage: score1x, backend.aux.src: cooldown1x, backend.aux.branch256: 1542, backend.aux.end256: 1928}
        - {stage: score2x, backend.aux.src: cooldown2x, backend.aux.branch256: 3084, backend.aux.end256: 3855}
        - {stage: score4x, backend.aux.src: cooldown4x, backend.aux.branch256: 6168, backend.aux.end256: 7710}
"""


def one(text, old, new):
    assert text.count(old) == 1, old
    return text.replace(old, new)


for opt in OPTS:
    t = open(os.path.join(SRC, f"phase1_{opt}.yaml")).read()
    t = t[t.index("defaults:"):t.index("\nsweep:") + 1]
    m = re.search(r'  # e\.g\. hyb100m_sweep_.*\n  # model _ .*\n  name: "(hyb100m_sweep_[^"]*)"', t)
    src_name = m.group(1)                                  # the phase 1 run name pattern
    new_name = src_name.replace("hyb100m_sweep_", "hyb100m_rescore_")
    t = t.replace(m.group(0), "  # e.g. " + f"hyb100m_rescore_{opt}_lr0.002_..._bs256_score4x" +
                  '  (= output dir name; scores the phase 1 run of the same name ending in cooldown4x)\n'
                  f'  name: "{new_name}"')
    t = one(t, "experiments/opt_scale/hyb100m_sweep/${job.name}", "experiments/opt_scale/hyb100m_rescore/${job.name}")
    t = one(t, 'WANDB_TAGS: "jupiter,sweep,', 'WANDB_TAGS: "jupiter,rescore,')
    t = one(t, f"    opt: {opt}\n", f"    opt: {opt}\n    src: cooldown4x    # phase 1 stage whose final checkpoint is scored (swept)\n")
    src_dir = "${backend.aux.base}/experiments/opt_scale/hyb100m_sweep/" + src_name.replace("${stage}", "${backend.aux.src}")
    t = one(t, '    load: "${job.base_output_dir}/ckpt"\n',
            f'    load: "{src_dir}/ckpt"   # read only\n'
            '    ckpt_step: ${backend.megatron.train_iters}   # the final step of that cooldown\n'
            '    skip_train: true            # evaluation only\n'
            '    dataloader_type: single     # validation sequences in fixed order from the start\n'
            '    override_opt_param_scheduler: true\n')
    t = re.sub(r'    eval_iters: "[^"]*"', f'    eval_iters: "${{oc.eval:\'{N_VALID} // ${{backend.aux.gbs}}\'}}"   # {N_VALID:,} sequences at every batch size', t, count=1)
    assert f"{N_VALID} //" in t
    t = re.sub(r"    save_extra_steps:.*\n(      - .*\n)+", "    save_extra_steps: []\n", t, count=1)
    t = re.sub(r"    non_persistent_save_interval: .*\n", "    non_persistent_save_interval: null\n", t, count=1)
    t = re.sub(r'    time: "12:00:00".*', '    time: "01:00:00"           # a scoring job takes about 11 minutes', t, count=1)
    assert 'time: "01:00:00"' in t
    path = os.path.join(HERE, f"rescore_{opt}.yaml")
    open(path, "w").write(HEADER.format(opt=opt, n=N_VALID) + t + SWEEP)
    print("wrote", os.path.relpath(path))

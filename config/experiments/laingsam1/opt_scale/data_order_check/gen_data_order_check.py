"""Generate the data-order check configs from the phase 1 sweep files.

Usage, from the repo root:
  python3 config/experiments/laingsam1/opt_scale/data_order_check/gen_data_order_check.py

Writes check_<optimizer>.yaml next to this script. What the check is and why: README.md here.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "sweep100m")

# optimizer -> (learning rate as written in yaml, as it appears in the phase 1 run name,
#               beta / momentum part of the phase 1 run name)
RUNS = {
    "adam": ("1.e-3", "0.001", "beta0.95"),
    "muon": ("2.e-3", "0.002", "mom0.95"),
    "muown_classical": ("4.e-3", "0.004", "mom0.95"),
}
GBS = 256
EVAL_ITERS = 100   # x 256 sequences = 25,600 validation sequences in the scoring jobs

HEADER = """# @package _global_
#
# data_order_check / {opt}: is the 4x cooldown of the phase 1 ladders hurt by repeated data?
# Background and how to read the result: README.md in this folder.
#
# Three jobs, all from the phase 1 run {opt}, lr {lr}, batch {gbs}:
#   0  fresh4x        the 4x cooldown again (step 6168 -> 7710), but with dataloader 'single',
#                     which continues with the part of the sample list the stable run never read
#   1  eval_repeated  scores the EXISTING phase 1 4x checkpoint on a fixed validation set
#   2  eval_fresh     scores the fresh4x checkpoint on the same set (starts when it exists)
#
# Output: $OPT_SCALE_BASE/experiments/opt_scale/hyb100m_dataorder/ (separate from the sweep).
# Nothing in the phase 1 folders is written to; their checkpoints are only read.
#
#   python scripts/run_autoexp.py --config-name experiments/laingsam1/opt_scale/data_order_check/check_{opt} --dry-run
#   python scripts/run_autoexp.py --config-name experiments/laingsam1/opt_scale/data_order_check/check_{opt}
#
# Generated by gen_data_order_check.py from ../sweep100m/phase1_{opt}.yaml.

"""

SWEEP = """sweep:
  type: product
  groups:
    - type: list
      defaults:
        backend.aux.gbs: {gbs}
        backend.megatron.lr: {lr}
        backend.aux.branch256: 6168
        backend.aux.end256: 7710
        backend.megatron.dataloader_type: single
        backend.megatron.save_extra_steps: []
        backend.megatron.non_persistent_save_interval: null
        backend.megatron.override_opt_param_scheduler: true
      configs:
        # The 4x cooldown on unseen data. Evaluation every 120 steps instead of 240: with
        # 'single' the validation reader does not wrap around, and at 240 the validation set
        # Megatron sizes for the job is one evaluation too short for the final one.
        - stage: fresh4x
          backend.megatron.load: "{sweep_dir}_stable/ckpt"
          backend.megatron.ckpt_step: 6168
          backend.megatron.eval_interval: 120
          slurm.sbatch.time: "05:00:00"
        # Scoring only (no training): the first {n_eval} validation sequences in fixed order.
        - stage: eval_repeated
          backend.megatron.skip_train: true
          backend.megatron.eval_iters: {eval_iters}
          backend.megatron.load: "{sweep_dir}_cooldown4x/ckpt"
          backend.megatron.ckpt_step: 7710
          slurm.sbatch.time: "01:00:00"
        - stage: eval_fresh
          backend.megatron.skip_train: true
          backend.megatron.eval_iters: {eval_iters}
          backend.megatron.load: "\\\\${{sibling.fresh4x.job.base_output_dir}}/ckpt"
          backend.megatron.ckpt_step: 7710
          slurm.sbatch.time: "01:00:00"
          job.start_condition:
            class_name: FileExistsCondition
            path: "\\\\${{sibling.fresh4x.job.base_output_dir}}/ckpt/iter_0007710/.metadata"
"""


def one(text, old, new):
    assert text.count(old) == 1, old
    return text.replace(old, new)


for opt, (lr, lr_name, hp) in RUNS.items():
    t = open(os.path.join(SRC, f"phase1_{opt}.yaml")).read()
    t = t[t.index("defaults:"):t.index("\nsweep:") + 1]
    t = re.sub(r'  # e\.g\. hyb100m_sweep_.*\n  # model _ .*\n  name: "hyb100m_sweep_[^"]*"',
               '  # e.g. hyb100m_dataorder_muon_lr0.002_bs256_fresh4x  (= wandb run name = output dir name)\n'
               '  name: "hyb100m_dataorder_${backend.aux.opt}_lr${backend.megatron.lr}_bs${backend.aux.gbs}_${stage}"',
               t, count=1)
    assert "hyb100m_dataorder_${backend.aux.opt}" in t
    t = one(t, "experiments/opt_scale/hyb100m_sweep/${job.name}", "experiments/opt_scale/hyb100m_dataorder/${job.name}")
    t = one(t, 'WANDB_TAGS: "jupiter,sweep,', 'WANDB_TAGS: "jupiter,data_order_check,')
    sweep_dir = "${backend.aux.base}/experiments/opt_scale/hyb100m_sweep/" + f"hyb100m_sweep_{opt}_lr{lr_name}_{hp}_bs{GBS}"
    out = HEADER.format(opt=opt, lr=lr, gbs=GBS) + t + SWEEP.format(
        gbs=GBS, lr=lr, sweep_dir=sweep_dir, eval_iters=EVAL_ITERS, n_eval=f"{EVAL_ITERS * GBS:,}")
    path = os.path.join(HERE, f"check_{opt}.yaml")
    open(path, "w").write(out)
    print("wrote", os.path.relpath(path))

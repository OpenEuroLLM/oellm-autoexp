#!/usr/bin/env python3
"""Generate the single-knob export -> eval pipeline config.

One config, one knob: aux.step (plus aux.model / aux.expert_dtype). The export
stage is sweep point 0 with an interpolated bench (aux.export_bench); the 438
eval rows are gated on the export's .downstream_ready marker.

The export command is composed in Hydra by interpolation from aux.export_bench
(which reuses scripts/korbi/hf_export/export_main_run_v2.sh, the fast
EXPORT_ONLY path); there is no separate wrapper script.

    python scripts/korbi/flag_eval/gen_pipeline_config.py > config/experiments/korbi/production/flag_eval_pipeline_mn5.yaml

Re-running on a new checkpoint is a re-submit with aux.step=<N>; nothing has to
be regenerated.
"""

import json
import sys

import yaml

SUITE = "config/eval_tasks/flag_evals.yaml"

EXPORT_BENCH = (
    "EXPORT_ONLY=1 EXPERT_DTYPE=${aux.expert_dtype} "
    "bash scripts/korbi/hf_export/export_main_run_v2.sh ${aux.model} ${aux.step} "
    "&& [ -d ${aux.export_dir} ] "  # the script's <name>_<step> must be the config's export dir
    '&& mkdir -p "$(dirname ${aux.view_dir})" '
    "&& { [ -d ${aux.view_dir} ] || python submodules/oellm-eval/containers/"
    "prepare_base_model_view.py --source ${aux.export_dir} --out ${aux.view_dir} --template identity; } "
    "&& { bash scripts/korbi/hf_export/refresh_code.sh ${aux.export_dir} ${aux.view_dir} || true; } "
    "&& touch ${aux.export_dir}/.downstream_ready"
)


def main() -> int:
    with open(SUITE) as f:
        data = yaml.safe_load(f)
    rows = data.get("tasks") or data.get("rows") or []
    if not rows:
        print("no rows in the suite", file=sys.stderr)
        return 2

    out: list[str] = []
    out.append("# @package _global_")
    out.append("# GENERATED by scripts/korbi/flag_eval/gen_pipeline_config.py -- do not edit.")
    out.append(f"# {len(rows)} FLAG rows (config/eval_tasks/flag_evals.yaml) + the export stage.")
    out.append("#")
    out.append("# One knob per checkpoint (re-submit, no regeneration):")
    out.append("#   aux.step=7000            (default below)")
    out.append("#   aux.model=ambitious_v4   ambitious | ambitious_v4 | ambitious_v4_hd256 | ambitious_v4_ldm | conservative")
    out.append("#                            (the export dir stem follows aux.model: ..._v4_2ph vs ..._v4_2ph_hd256)")
    out.append("#   aux.expert_dtype=fp8     bf16 | fp8")
    out.append("#")
    out.append("# Stage 0 (sweep point 0) runs aux.export_bench: the fast parallel DCP reader with")
    out.append("# EXPORT_ONLY=1 (no equivalence checks -- the architecture is proven), then the")
    out.append("# identity chat-template view, refresh_code, and <export>/.downstream_ready.")
    out.append("# Stages 1..N are the eval rows of flag_eval_oellm_mn5; they wait for that marker")
    out.append("# (persistent_pass), so a re-submit of the same checkpoint is idempotent.")
    out.append("#")
    out.append("#   scripts/korbi/mn5_autoexp.sh scripts/run_autoexp.py --no-monitor \\")
    out.append("#       --monitor-state-dir $R/pool_state --pool <pool> \\")
    out.append("#       --config-name experiments/korbi/production/flag_eval_pipeline_mn5 \\")
    out.append("#       aux.step=7000 --yes")
    out.append("defaults:")
    out.append("  - flag_eval_oellm_mn5")
    out.append("  - _self_")
    out.append("")
    out.append("aux:")
    out.append("  step: 7000")
    out.append("  model: ambitious_v4")
    out.append("  expert_dtype: fp8")
    out.append("  export_root: /gpfs/scratch/ehpc533/hybrid_nucleus/hf_exports")
    out.append("  # export dir stem per model lineage; must match the `name` in export_main_run_v2.sh")
    out.append("  stems:")
    out.append("    ambitious_v4: ambitious_v4_2ph")
    out.append("    ambitious_v4_hd256: ambitious_v4_2ph_hd256")
    out.append("  export: ${aux.stems.${aux.model}}_fp8_${aux.step}")
    out.append("  export_dir: ${aux.export_root}/${aux.export}")
    out.append("  view_dir: /gpfs/scratch/ehpc533/hybrid_nucleus/views/identity/${aux.export}")
    out.append(f"  export_bench: {json.dumps(EXPORT_BENCH)}")
    out.append("  # placeholders so the base config resolves; every sweep point overrides them")
    out.append("  name: pipeline_base")
    out.append('  task: ""')
    out.append("  n_shot: 0")
    out.append("  suite: pipeline")
    out.append("")
    out.append("# Eval env: keep the batch/graph ceilings that fit 16 concurrent jobs; the")
    out.append("# full-decode CUDA-graph / UVA-Engram switches stay off (they OOMed the")
    out.append("# 16-node eval and need a TP4 validation of their own). Override per run.")
    out.append("backend:")
    out.append("  env:")
    out.append('    OELLM_HF_REFRESH_CODE: "1"')
    out.append('    OELLM_LIGHTEVAL_MAX_NUM_SEQS: "64"')
    out.append('    OELLM_LIGHTEVAL_GRAPH_MAX_ROWS: "64"')
    out.append('    OELLM_EVALCHEMY_MAX_NUM_SEQS: "64"')
    out.append('    OELLM_EVALCHEMY_GRAPH_MAX_ROWS: "64"')
    out.append("")
    out.append("sweep:")
    out.append("  type: list")
    out.append("  store_sweep_json: true")
    out.append("  groups:")
    out.append("    # stage 0 = point 0 (export); stages 1..N = the eval rows, gated on the marker.")
    out.append("    # One list group: the sweep filter walker does not support sibling groups.")
    out.append("    - type: list")
    out.append("      configs:")
    out.append("        - aux.row: 0")
    out.append('          aux.name: "export_${aux.export}"')
    out.append('          aux.task: "export"')
    out.append('          aux.suite: "pipeline"')
    out.append("          aux.n_shot: 0")
    out.append("          aux.bench: ${aux.export_bench}")
    out.append("          job.est_step_time_s: 1800")
    out.append('          slurm.sbatch.time: "00:30:00"')
    out.append("          job.metadata.pool_priority: 50")
    out.append(
        '          backend.env.PYTHONPATH: ".:submodules/Megatron-LM:flash-linear-attention:'
        "submodules/cute_kernels:${aux.images.${aux.image}.libs}:${aux.hybrid_env}/pylibs_hfx\""
    )
    for i, row in enumerate(rows):
        name = f"oellm${{aux.step}}_{i}_{row['suite']}"
        out.append(f"        - aux.row: {i}")
        out.append(f"          aux.name: {json.dumps(name)}")
        out.append(f"          aux.task: {json.dumps(row['task'])}")
        out.append(f"          aux.n_shot: {row['n_shot']}")
        out.append(f"          aux.suite: {json.dumps(row['suite'])}")
        out.append("          job.start_condition:")
        out.append("            class_name: FileExistsCondition")
        out.append('            path: "${aux.export_dir}/.downstream_ready"')
        out.append("            persistent_pass: true")
    out.append("")
    sys.stdout.write("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Generate config/experiments/korbi/recall_surgery/small31_readout_jupiter.yaml: one 1-node readout job
(small31_readout.sh: HF export + critical / recall / RULER rows + valid loss) per small31 base run and persistent
checkpoint (docs/recall_surgery_ambitious.md §14), each gated on its save (FileExistsCondition on the checkpoint's
.metadata, written last by the DCP save): enqueued once into jupiter_pool_small16, the pool monitor starts every
readout as soon as its checkpoint appears -- the per-checkpoint trigger, no daemon.

    python scripts/korbi/recall_surgery/gen_small31_readout.py
"""

from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
OUT = REPO / "config/experiments/korbi/recall_surgery/small31_readout_jupiter.yaml"
ROOT = "/e/scratch/e-sta-openeurollm/poeppel1/recall_surgery/small31"
ARMS = ["b7", "r3", "r3p"]
# the log-spaced token marks of small31_jupiter (save_extra_steps, 0.25 / 0.5 / 1 / 2 / 4 / 8 / 16 BT) + the end (20 BT)
STEPS = [477, 954, 1907, 3815, 7629, 15259, 30518, 38146]

HEADER = """# @package _global_
# GENERATED by scripts/korbi/recall_surgery/gen_small31_readout.py -- edit the generator, not this file.
# Phase-1 readouts of the small-scale testbed (docs/recall_surgery_ambitious.md §14): one 1-node job per base run
# (b7 / r3 / r3p) and persistent checkpoint, scripts/korbi/recall_surgery/small31_readout.sh in the training image
# (HF export -> CoQA / Winogrande / SQuAD v2 10-shot (4000 docs) / SWDE / FDA / squad_completion / RULER 4k subset /
# v8ml-valid loss, one GPU per row group). Each job waits for its checkpoint's .metadata (start_condition): enqueue
# once, the pool runs each readout when its save appears. Low priority (the bases first), excluded nodes first.
#   ssh jupiter 'cd ~/work/Projects/oellm-autoexp-hybrid && PYTHONPATH=. .venv/bin/python scripts/run_autoexp.py \\
#       --no-monitor --monitor-state-dir /e/scratch/e-sta-openeurollm/poeppel1/pool_state \\
#       --pool /e/scratch/e-sta-openeurollm/poeppel1/pools/jupiter_pool_small16 \\
#       --config-name experiments/korbi/recall_surgery/small31_readout_jupiter --yes'
#   table: python scripts/korbi/recall_surgery/small31_table.py   (login node, any python)
defaults:
  - ../../base
  - /backend: bash
  - /container: jupiter
  - /slurm: jupiter
  - _self_

aux:
  arm: b7
  step: 477
  only: []
  root: """ + ROOT + """

container:
  image: /e/project1/e-sta-openeurollm/poeppel1/container_cache/MegatronTraining-JUPITER_pt2512_aarch64_202602231451.sif

backend:
  command: bash scripts/korbi/recall_surgery/small31_readout.sh
  env:
    ARM: ${aux.arm}
    STEP: ${aux.step}
    ROOT: ${aux.root}
    # wonderwords + accelerate (not in the image) from the eval library dir (small31_precache.sh)
    PYTHONPATH: ".:submodules/Megatron-LM:flash-linear-attention:submodules/cute_kernels:/e/project1/e-sta-openeurollm/poeppel1/pylibs_ruler"
    HF_HOME: /e/scratch/e-sta-openeurollm/poeppel1/cache/hf
    NLTK_DATA: /e/scratch/e-sta-openeurollm/poeppel1/cache/nltk_data
    HF_DATASETS_OFFLINE: "1"
    HF_HUB_OFFLINE: "1"
    TRANSFORMERS_OFFLINE: "1"
    TOKENIZERS_PARALLELISM: "false"
    TRITON_LIBCUDA_PATH: /.singularity.d/libs
    TRITON_CACHE_DIR: /e/scratch/e-sta-openeurollm/poeppel1/cache/triton_small31

slurm:
  exclude_file: ${aux.root}/exclude_nodes.txt
  sbatch:
    nodes: 1
    time: "12:00:00"
    account: e-ext-2025e02-108
    partition: booster

job:
  name: s31ro_${aux.arm}_${aux.step}
  base_output_dir: ${aux.root}/readout_logs/${aux.arm}_${aux.step}
  est_step_time_s: 3600
  metadata:
    pool_priority: 20
    pool_use_excluded_nodes: true
    pool_singleton: null

sweep:
  type: product
  store_sweep_json: true
  filter: "\\\\${oc.eval:'len(\\\\${aux.only}) == 0 or \\"\\\\${aux.arm}_\\\\${aux.step}\\" in \\\\${aux.only}'}"
  groups:
    - type: list
      configs:"""


def main():
    lines = [HEADER]
    for arm in ARMS:
        for step in STEPS:
            meta = f"{ROOT}/{arm}/ckpt/iter_{step:07d}/.metadata"
            lines += [f"        - aux.arm: {arm}", f"          aux.step: {step}",
                      "          job.start_condition:", "            class_name: FileExistsCondition",
                      f"            path: {meta}"]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT}: {len(ARMS) * len(STEPS)} readouts")


if __name__ == "__main__":
    main()

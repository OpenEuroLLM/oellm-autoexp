"""Generate the expert-parallel / fp8 speed suites (config/experiments/korbi/hybrid_speed/ep_*_mn5.yaml).

    python scripts/korbi/ep_speed/gen_ep_suites.py

Goal (docs/ep_fp8_speed.md): test, integrate and tune every EP backend of the hybrid-ep image
(alltoall, flex/HybridEP, flex/DeepEP, flex/ncclep, MoonEP) and fp8 for the 3B-active hybrid
MoE, towards > 250 TFLOP/s/GPU at the production scale. Every arm runs under the in-job
watchdog (templates/marenostrum_watchdog.sbatch): GPU memory trace, and a hang (no iteration
for WATCHDOG_STALL_S) is killed with py-spy stacks instead of burning the wall time.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "hybrid_speed"))
import gen_suites  # noqa: E402
from gen_suites import B, vpp_pattern  # noqa: E402,F401


def dump(fname, doc, extra, arms):
    gen_suites.dump(fname, doc, extra, arms)
    path = gen_suites.OUT / fname
    path.write_text(path.read_text().replace(
        "GENERATED by scripts/korbi/hybrid_speed/gen_suites.py",
        "GENERATED by scripts/korbi/ep_speed/gen_ep_suites.py", 1))

# The production model's layer recipe (docs/hybrid_moe_3b_campaign.md §11.4 / prod_width):
# CKDA 5:1 (reference CKDA, low-rank output gate), attention NoPE + qk-norm + XSA + gate, MoE
# with one shared expert of the expert width, sigmoid router + expert bias + aux 1e-4.
RECIPE = {B + "linear_beta_max": 2.0, B + "linear_gate_activation": "signed_sigmoid2",
          B + "linear_gate_init_style": "shipped", B + "linear_output_gate": "lowrank",
          B + "linear_drop_qkv_silu": True,
          B + "position_embedding_type": "none", B + "attention_output_gate": True,
          B + "exclusive_self_attention": True,
          B + "moe_router_score_function": "sigmoid", B + "moe_router_enable_expert_bias": True,
          B + "moe_router_bias_update_rate": 1e-3, B + "moe_aux_loss_coeff": 1e-4,
          B + "moe_router_fusion": True, "backend.env.CUDA_DEVICE_MAX_CONNECTIONS": "8"}
# routed residual, 2 of 8 streams (reversible, sublayer recompute): the preferred residual
ROUTED = {B + "mhc": True, B + "mhc_expansion_rate": 8, B + "mhc_routed_topk": 2,
          B + "mhc_routed_reversible": True}
PROD = {B + "num_experts": 160, B + "moe_ffn_hidden_size": 768, B + "moe_router_topk": 5,
        B + "moe_shared_expert_intermediate_size": 768}

# dispatchers
A2A = {B + "moe_token_dispatcher_type": "alltoall"}
HEP = {B + "moe_token_dispatcher_type": "flex", B + "moe_flex_dispatcher_backend": "hybridep"}
DEP = {B + "moe_token_dispatcher_type": "flex", B + "moe_flex_dispatcher_backend": "deepep"}
NEP = {B + "moe_token_dispatcher_type": "flex", B + "moe_flex_dispatcher_backend": "ncclep",
       B + "moe_expert_rank_capacity_factor": 1.5}
OVL = {B + "overlap_moe_expert_parallel_comm": True}
OPF = {B + "use_transformer_engine_op_fuser": True}
FORCE = {B + "moe_router_force_load_balancing": True}
# Megatron takes the op-fuser path for SwiGLU only with NVTE_CUTEDSL_FUSED_GROUPED_MLP=1 (the
# sm100 CuTe kernel's switch); on H100 TE then runs GroupedLinear -> ScaledSwiGLU -> GroupedLinear
# through its graph-safe grouped-tensor path (one group_quantize + one cuBLASLt grouped GEMM per
# linear, CUDA m_splits: no host sync; bf16, fp8 current scaling, fp8 block scaling on cuBLASLt
# >= 13.6, the image has 13.8). The env goes into the srun line: an array of its own.
OPFX = dict(OPF, **{"backend.env.NVTE_CUTEDSL_FUSED_GROUPED_MLP": "1", "aux.array_tag": "_opfx"})
# fp8 recipes (first / last layer bf16 is meaningless in a 6-block slice: all fp8 here)
FP8T = {B + "fp8": "hybrid", B + "fp8_recipe": "tensorwise", B + "fp8_param_gather": False,
        B + "moe_router_padding_for_quantization": True}
FP8B = dict(FP8T, **{B + "fp8_recipe": "blockwise"})
FP8D = dict(FP8T, **{B + "fp8_recipe": "delayed"})


def arms_builder():
    arms = []

    def arm(name, comment, *dicts):
        merged = {}
        for d in dicts:
            merged.update(d)
        arms.append((name, comment, merged))

    return arms, arm


def ep_slice():
    """One node, one 5:1 period (6 blocks) at the production layer shapes (hidden 2048,
    160 x 768 top-5 + shared 768, EP4: 40 experts per GPU), 8k tokens, mbs 1, no recompute,
    PP1, vocabulary 32k (the 262k LM head would be 65 % of a 6-block slice's FLOPs). Phase A:
    does every backend run, train the same loss, and how fast is it, in bf16 and fp8."""
    arms, arm = arms_builder()
    base = dict(RECIPE, **PROD)
    arm("a2a", "alltoall dispatcher", base, A2A)
    arm("hep", "flex / HybridEP (the production reference)", base, HEP)
    arm("hep_fuse", "HybridEP with the permute fused into the dispatch kernel", base, HEP,
        {B + "moe_permute_fusion_into_hybridep": True})
    arm("dep", "flex / DeepEP (normal kernels, NVLink)", base, DEP)
    arm("nep", "flex / ncclep (TE NCCL-EP), rank capacity 1.5", base, NEP)
    arm("hep_opf", "HybridEP + TE op-fuser grouped MLP", base, HEP, OPF)
    arm("hep_ovl", "HybridEP + EP a2a overlap (1F1B-style, plain residual only)", base, HEP, OVL)
    arm("dep_ovl", "DeepEP + EP a2a overlap", base, DEP, OVL)
    arm("hep_force", "HybridEP, forced balanced routing (upper bound of load balancing)", base, HEP,
        FORCE)
    arm("hep_fp8t", "HybridEP, fp8 tensorwise + router padding", base, HEP, FP8T)
    arm("hep_fp8b", "HybridEP, fp8 blockwise (1x128 / 128x128) + router padding", base, HEP, FP8B)
    arm("hep_fp8b_opf", "HybridEP, fp8 blockwise + op-fuser", base, HEP, FP8B, OPF)
    arm("dep_fp8b", "DeepEP, fp8 blockwise + router padding", base, DEP, FP8B)
    arm("a2a_fp8b", "alltoall, fp8 blockwise + router padding", base, A2A, FP8B)
    arm("hep_opfx", "HybridEP + op-fuser through TE's grouped-tensor path (bf16)", base, HEP, OPFX)
    arm("hep_fp8t_opfx", "HybridEP + op-fuser grouped-tensor path, fp8 tensorwise", base, HEP, FP8T,
        OPFX)
    arm("hep_fp8b_opfx", "HybridEP + op-fuser grouped-tensor path, fp8 blockwise", base, HEP, FP8B,
        OPFX)
    # the routed residual (the production residual) with the three dispatchers
    arm("hep_routed", "HybridEP + routed residual 2 of 8", base, HEP, ROUTED)
    arm("dep_routed", "DeepEP + routed residual 2 of 8", base, DEP, ROUTED)
    arm("a2a_routed", "alltoall + routed residual 2 of 8", base, A2A, ROUTED)
    return arms


MOON = {B + "moe_token_dispatcher_type": "flex", B + "moe_flex_dispatcher_backend": "moonep"}
# rank 0 torch profile of steps 20-22 (kernel_summary.py); the throughput is read from steps < 20
PROF = {B + "profile": True, B + "use_pytorch_profiler": True, B + "profile_ranks": [0],
        B + "profile_step_start": 20, B + "profile_step_end": 22}


def ep_slice2():
    """Phase A, second round: the fixed arms (ncclep bootstrap on TE 2.19, alltoall + router
    padding), MoonEP, and rank-0 profiles of the grouped-tensor path in bf16 / fp8."""
    arms, arm = arms_builder()
    base = dict(RECIPE, **PROD)
    arm("nep", "flex / ncclep (TE NCCL-EP), rank capacity 1.5", base, NEP)
    arm("a2a_fp8b", "alltoall, fp8 blockwise + router padding", base, A2A, FP8B)
    arm("moon", "MoonEP (balanced dispatch, prefetched redundant experts), bf16", base, MOON)
    arm("moon_routed", "MoonEP + routed residual 2 of 8", base, MOON, ROUTED)
    arm("hep_opfx_routed", "HybridEP + grouped-tensor op-fuser path + routed residual", base, HEP,
        OPFX, ROUTED)
    arm("prof_hep", "profile: HybridEP bf16 (unfused TEGroupedMLP)", base, HEP, PROF)
    arm("prof_hep_opfx", "profile: HybridEP bf16, grouped-tensor path", base, HEP, OPFX, PROF)
    arm("prof_hep_fp8b_opfx", "profile: HybridEP fp8 blockwise, grouped-tensor path", base, HEP,
        FP8B, OPFX, PROF)
    arm("prof_moon", "profile: MoonEP bf16", base, MOON, PROF)
    return arms



def with_engram(pattern: str, before_blocks) -> str:
    """Insert an Engram layer (`N`) before the given 0-indexed blocks (mixer + MoE) of a
    pipe-separated hybrid pattern."""
    out, block = [], 0
    for ch in pattern:
        if ch not in "E|":
            if block in before_blocks:
                out.append("N")
            block += 1
        out.append(ch)
    return "".join(out)



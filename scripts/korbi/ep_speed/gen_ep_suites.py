def arms_builder():
    arms = []

    def arm(name, comment, *dicts):
        merged = {}
        for d in dicts:
            merged.update(d)
        arms.append((name, comment, merged))

    return arms, arm


def ep_slice():
    """One node, one 5:1 period (6 blocks) at the production layer shapes (hidden 2048,
    160 x 768 top-5 + shared 768, EP4: 40 experts per GPU), 8k tokens, mbs 1, no recompute,
    PP1, vocabulary 32k (the 262k LM head would be 65 % of a 6-block slice's FLOPs). Phase A:
    does every backend run, train the same loss, and how fast is it, in bf16 and fp8."""
    arms, arm = arms_builder()
    base = dict(RECIPE, **PROD)
    arm("a2a", "alltoall dispatcher", base, A2A)
    arm("hep", "flex / HybridEP (the production reference)", base, HEP)
    arm("hep_fuse", "HybridEP with the permute fused into the dispatch kernel", base, HEP,
        {B + "moe_permute_fusion_into_hybridep": True})
    arm("dep", "flex / DeepEP (normal kernels, NVLink)", base, DEP)
    arm("nep", "flex / ncclep (TE NCCL-EP), rank capacity 1.5", base, NEP)
    arm("hep_opf", "HybridEP + TE op-fuser grouped MLP", base, HEP, OPF)
    arm("hep_ovl", "HybridEP + EP a2a overlap (1F1B-style, plain residual only)", base, HEP, OVL)
    arm("dep_ovl", "DeepEP + EP a2a overlap", base, DEP, OVL)
    arm("hep_force", "HybridEP, forced balanced routing (upper bound of load balancing)", base, HEP,
        FORCE)
    arm("hep_fp8t", "HybridEP, fp8 tensorwise + router padding", base, HEP, FP8T)
    arm("hep_fp8b", "HybridEP, fp8 blockwise (1x128 / 128x128) + router padding", base, HEP, FP8B)
    arm("hep_fp8b_opf", "HybridEP, fp8 blockwise + op-fuser", base, HEP, FP8B, OPF)
    arm("dep_fp8b", "DeepEP, fp8 blockwise + router padding", base, DEP, FP8B)
    arm("a2a_fp8b", "alltoall, fp8 blockwise + router padding", base, A2A, FP8B)

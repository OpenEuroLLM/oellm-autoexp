#!/usr/bin/env python3
"""Sweep configs of one-node embedding jobs, one per stream chunk (config/experiments/korbi/cross_doc_seqs/
cds_embed_chunk_mn5.yaml), in batches -- each batch is one run_autoexp call (the login node kills a process after
300 s of CPU, so thousands of jobs are enqueued in batches of ~100).

    gen_embed_chunks.py --from 63000 --to 236733 --batch 100 [--emb q3e128 --dim 128]
"""

import argparse
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "..", "config", "experiments", "korbi", "cross_doc_seqs", "chunks")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--from", dest="a", type=int, required=True)
    ap.add_argument("--to", dest="b", type=int, required=True)
    ap.add_argument("--chunk", type=int, default=100)
    ap.add_argument("--batch", type=int, default=100, help="chunks (jobs) per generated config")
    ap.add_argument("--emb", default="q3e128")
    ap.add_argument("--dim", type=int, default=128)
    a = ap.parse_args()
    starts = list(range(a.a, a.b, a.chunk))
    os.makedirs(OUT, exist_ok=True)
    for i in range(0, len(starts), a.batch):
        part = starts[i:i + a.batch]
        lo, hi = part[0], min(part[-1] + a.chunk, a.b)
        name = f"emb_{a.emb}_{lo:07d}_{hi:07d}"
        lines = ["# @package _global_", f"# generated by scripts/korbi/cross_doc_seqs/gen_embed_chunks.py: chunks {lo}-{hi}",
                 "defaults:", "  - ../cds_embed_chunk_mn5", "  - _self_", "", "aux:", f"  emb_name: {a.emb}",
                 f"  emb_dim: {a.dim}", "", "sweep:", "  type: product", "  groups:", "    - type: list", "      configs:"]
        for s in part:
            lines.append(f"        - aux.from_ckpt: {s}")
            lines.append(f"          aux.steps: {min(a.chunk, a.b - s)}")
        open(os.path.join(OUT, name + ".yaml"), "w").write("\n".join(lines) + "\n")
        print(name, len(part))


if __name__ == "__main__":
    main()

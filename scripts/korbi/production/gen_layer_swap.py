#!/usr/bin/env python3
"""Generate the layer-swap test configs (docs/recall_surgery_ambitious.md §11) from one variant matrix:

    config/experiments/korbi/production/layer_swap_build_mn5.yaml       1-node pool jobs: layer_swap_build.sh per arm
    config/experiments/korbi/production/fixedvalid_eval_layer_swap_mn5.yaml   8-node eval-only fixed-valid losses
                                                                         (per-token dumps) per arm + each base

    python scripts/korbi/production/gen_layer_swap.py

Arms: b<B>_base (the base checkpoint itself), b<B>_<layers>_zero (the sublayers' output projections zeroed) and
b<B>_<layers>_d<D> (the sublayers from donor step D). All checkpoints are the hd256 run's frozen ckpt_eval copies
(same architecture from 9815 on). Compare each arm's dump with its base's:
    python scripts/korbi/production/duplicate_kv_groups.py compare-dumps \\
        /gpfs/scratch/ehpc533/hybrid_nucleus/fixedvalid_eval/layer_swap/b23500_base/token_dump \\
        /gpfs/scratch/ehpc533/hybrid_nucleus/fixedvalid_eval/layer_swap/<arm>/token_dump
"""

from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
OUT = REPO / "config/experiments/korbi/production"
ROOT = "/gpfs/scratch/ehpc533/hybrid_nucleus/production/layer_swap"
PHASE2_FROM = 23691  # the main run's phase transition (8k -> 64k)
SRC = "/gpfs/scratch/ehpc533/hybrid_nucleus/production/main_mhc4/ambitious_e360_eng80_v4_2ph_hd256/ckpt_eval"

# base step -> (donor steps, layer sets swapped from every donor, layer sets zeroed)
MATRIX = {
    23500: ([23000, 21000, 18000, 15000, 10000], ["attn6", "attn1", "ckda1", "mixall"], ["attn6", "attn1", "ckda1"]),
    35603: ([32000, 23500, 10000], ["attn6", "mixall"], ["attn6"]),
}


def arms():
    for base, (donors, swaps, zeros) in MATRIX.items():
        yield {"arm": f"b{base}_base", "base": base, "donor": None, "layers": None}
        for layers in zeros:
            yield {"arm": f"b{base}_{layers}_zero", "base": base, "donor": "zero", "layers": layers}
        for donor in donors:
            for layers in swaps:
                yield {"arm": f"b{base}_{layers}_d{donor}", "base": base, "donor": donor, "layers": layers}


HEADER = "# @package _global_\n# GENERATED by scripts/korbi/production/gen_layer_swap.py -- edit the generator, not this file.\n"


def build_yaml(rows):
    lines = [HEADER, """# Layer-swap test checkpoints (docs/recall_surgery_ambitious.md §11), one 1-node pool job per arm:
# scripts/korbi/production/layer_swap_build.sh (layer_swap.py build) in the training image, from a synced snapshot.
# Output: <aux.root>/<arm>/ckpt/iter_<base> (hard links of the base + the swapped / zeroed model tensors +
# layer_swap.json) and its tracker (= base step, after the read-back); logs <aux.root>/build_logs/<arm>.
#   cd $R/autoexp_<snapshot> && scripts/korbi/mn5_autoexp.sh scripts/run_autoexp.py --no-monitor \\
#       --monitor-state-dir $R/pool_state --pool /gpfs/scratch/ehpc533/hybrid_nucleus/pools/mn5_pool_p264 \\
#       --config-name experiments/korbi/production/layer_swap_build_mn5 --yes
defaults:
  - ../hybrid_speed/kernel_tests_mn5
  - _self_

aux:
  name: layer_swap_build
  # defaults = the first arm (the base config resolves before the sweep entries apply)
  arm: b23500_attn6_zero
  base_it: 23500
  donor_it: zero
  layers: attn6
  only: []
  root: """ + ROOT + """
  src: """ + SRC + """
  tests: ""
  bench: ""

backend:
  command: bash scripts/korbi/production/layer_swap_build.sh
  env:
    ARM: ${aux.arm}
    BASE_IT: ${aux.base_it}
    DONOR_IT: ${aux.donor_it}
    LAYERS: ${aux.layers}
    ROOT: ${aux.root}
    SRC: ${aux.src}

job:
  name: ls_${aux.arm}
  base_output_dir: ${aux.root}/build_logs/${aux.arm}
  est_step_time_s: 1200
  metadata:
    pool_priority: 90
    pool_use_excluded_nodes: false
    pool_singleton: null

slurm:
  sbatch:
    time: "01:00:00"
    account: cns144
    qos: acc_xehpc

sweep:
  type: product
  store_sweep_json: true
  filter: "\\\\${oc.eval:'len(\\\\${aux.only}) == 0 or \\"\\\\${aux.arm}\\" in \\\\${aux.only}'}"
  groups:
    - type: list
      configs:"""]
    for r in rows:
        if r["donor"] is None:
            continue
        lines.append(f"        - {{aux.arm: {r['arm']}, aux.base_it: {r['base']}, aux.donor_it: {r['donor']}, "
                     f"aux.layers: {r['layers']}}}")
    return "\n".join(lines) + "\n"


def eval_yaml(rows):
    lines = [HEADER, """# Eval-only fixed-valid losses of the layer-swap test (docs/recall_surgery_ambitious.md §11): every arm of
# layer_swap_build_mn5 and each base, the setup of fixedvalid_eval_kvdup_v4_mn5 (8 nodes, EP 8, no optimizer load,
# per-token dumps MEGATRON_EVAL_TOKEN_DUMP -> /gpfs/scratch/ehpc533/hybrid_nucleus/fixedvalid_eval/layer_swap/<arm>/
# token_dump). Built arms wait for their tracker. Compare with the base (duplicate_kv_groups.py compare-dumps).
#   cd $R/autoexp_<snapshot> && scripts/korbi/mn5_autoexp.sh scripts/run_autoexp.py --no-monitor \\
#       --monitor-state-dir $R/pool_state --pool /gpfs/scratch/ehpc533/hybrid_nucleus/pools/mn5_pool_p264 \\
#       --config-name experiments/korbi/production/fixedvalid_eval_layer_swap_mn5 --yes
defaults:
  - fixedvalid_eval_kvdup_v4_mn5
  - _self_

aux:
  suite: layer_swap
  arm: b23500_base

job:
  metadata:
    pool_priority: 60

sweep:
  type: product
  store_sweep_json: true
  filter: \\${oc.eval:'len(\\${aux.only}) == 0 or "\\${aux.arm}" in \\${aux.only}'}
  groups:
  - type: list
    configs:"""]
    for r in rows:
        lines.append(f"    - aux.arm: {r['arm']}")
        lines.append(f"      backend.megatron.ckpt_step: {r['base']}")
        lines.append(f"      backend.megatron.train_iters: {r['base']}")
        if r["base"] > PHASE2_FROM:  # past the last phase transition: Megatron's phase sample count needs a next one
            lines.append("      backend.megatron.phase_transition_iterations: null  # eval only: no curriculum")
            lines.append("      backend.megatron.phase_transition_variable_batch: false")
        if r["donor"] is None:
            lines.append(f"      backend.megatron.load: {SRC}")
            continue
        lines.append(f"      backend.megatron.load: {ROOT}/{r['arm']}/ckpt")
        lines.append("      job.start_condition:")
        lines.append("        class_name: FileContentCondition")
        lines.append(f"        path: {ROOT}/{r['arm']}/ckpt/latest_checkpointed_iteration.txt")
        lines.append(f"        pattern: \"^\\\\s*{r['base']}\\\\s*$\"")
        lines.append("        mode: regex")
        lines.append("        persistent_pass: true")
    return "\n".join(lines) + "\n"


def main():
    rows = list(arms())
    (OUT / "layer_swap_build_mn5.yaml").write_text(build_yaml(rows))
    (OUT / "fixedvalid_eval_layer_swap_mn5.yaml").write_text(eval_yaml(rows))
    n_build = sum(r["donor"] is not None for r in rows)
    print(f"{len(rows)} eval arms, {n_build} builds")


if __name__ == "__main__":
    main()

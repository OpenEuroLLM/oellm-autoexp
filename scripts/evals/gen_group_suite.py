#!/usr/bin/env python3
"""A suite file (rows.suite_file) with the FLAG rows of some summarize-evals categories, plus extra suite files.

The categories are summarize-evals' own (tasks.get_task_group, the revision flag_summary_mn5.sh pins), so a
focused round is scored like the full one. Example (the ckda_branch post-fit round, 2026-11-10):

    python scripts/evals/gen_group_suite.py --groups reading,commonsense,math \\
        --extra config/eval_tasks/recall_evals.yaml --out config/eval_tasks/ckdab_focus.yaml \\
        --summarize-evals dump/flag_summaries/.cache/summarize-evals
"""

import argparse
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--groups", required=True, help="comma-separated summarize-evals categories")
    ap.add_argument("--flag", default="config/eval_tasks/flag_evals.yaml", help="the FLAG rows")
    ap.add_argument("--extra", action="append", default=[], help="suite files appended as they are")
    ap.add_argument("--out", required=True)
    ap.add_argument("--summarize-evals", required=True, help="a summarize-evals checkout (tasks.py)")
    a = ap.parse_args(argv)
    sys.path.insert(0, str(Path(a.summarize_evals).resolve()))
    from tasks import get_task_group, parse_task

    groups = set(a.groups.split(","))
    flag = yaml.safe_load((REPO / a.flag).read_text())
    rows, counts = [], {g: 0 for g in groups}
    for r in flag["tasks"]:
        try:
            group = get_task_group(parse_task(r["task"])[0])
        except Exception:  # a task summarize-evals does not know (not in any category)
            continue
        if group in groups:
            rows.append(r)
            counts[group] += 1
    for extra in a.extra:
        rows += yaml.safe_load((REPO / extra).read_text())["tasks"]
    names = [r["name"] for r in rows]
    if len(set(names)) != len(names):
        raise SystemExit("duplicate row names")
    header = (f"# GENERATED by scripts/evals/gen_group_suite.py --groups {a.groups} "
              + "".join(f"--extra {e} " for e in a.extra) + f"-- the FLAG rows of these categories\n"
              f"# ({', '.join(f'{g} {n}' for g, n in sorted(counts.items()))}) + the extra suites; from {a.flag}"
              f" (oellm_eval_rev {flag.get('oellm_eval_rev')}).\n")
    body = yaml.safe_dump({"count": len(rows), "tasks": rows}, sort_keys=False, width=200, default_flow_style=None)
    (REPO / a.out).write_text(header + body)
    print(f"wrote {a.out}: {len(rows)} rows {counts} + {len(rows) - sum(counts.values())} extra")
    return 0


if __name__ == "__main__":
    sys.exit(main())

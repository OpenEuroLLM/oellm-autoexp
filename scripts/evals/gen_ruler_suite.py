#!/usr/bin/env python3
"""Generate the RULER long-context suite files (docs/recall_surgery_ambitious.md §17): one row per (task, context
length), task name "<ruler task>__L<length>" (oellm-eval lm_eval_queue.ruler_row: the length goes to the task's
metadata, 100 documents per row via OELLM_RULER_LIMIT). Tasks: the eight needle-in-a-haystack variants and variable
tracking (no network; the QA tasks download their data at build time and cwe/fwe need extra packages).

    python scripts/evals/gen_ruler_suite.py   # -> config/eval_tasks/ruler_long.yaml (4k-64k), ruler_long_32k.yaml (4k-32k)

Launch with lm_eval.split_s=0 (a RULER row is never split into document parts).
"""
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
TASKS = ["niah_single_1", "niah_single_2", "niah_single_3", "niah_multikey_1", "niah_multikey_2", "niah_multikey_3",
         "niah_multivalue", "niah_multiquery", "ruler_vt"]
SUITES = {"ruler_long": [4096, 8192, 16384, 32768, 65536], "ruler_long_32k": [4096, 8192, 16384, 32768]}


def main():
    for name, lengths in SUITES.items():
        rows = [(t, n) for n in lengths for t in TASKS]
        lines = [f"# GENERATED by scripts/evals/gen_ruler_suite.py -- RULER at {', '.join(str(n) for n in lengths)} tokens;",
                 "# one row per (task, length): task <ruler task>__L<length>. Launch with lm_eval.split_s=0.",
                 f"count: {len(rows)}", "tasks:"]
        for i, (t, n) in enumerate(rows):
            lines.append(f"  - {{name: \"vllm/{t}__L{n}/0\", half: \"vllm\", row: {i}, task: \"{t}__L{n}\", n_shot: 0, "
                         f"suite: \"lm-eval-harness\"}}")
        (REPO / f"config/eval_tasks/{name}.yaml").write_text("\n".join(lines) + "\n")
        print(name, len(rows), "rows")


if __name__ == "__main__":
    main()
